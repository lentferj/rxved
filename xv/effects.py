"""What each effect algorithm's parameters are, and how they read.

Transcribed from the XV-2020 Editor's script file, the only machine-readable
copy of these tables. The Owner's Manual prints the *ranges* but not the
*steps*, and the steps are not a formula: the chorus RATE runs 0.05-5.00 Hz
in 0.05 steps, then 5.10-7.00 in 0.10, then 7.50-10.00 in 0.50. The editor
carries each one as a display string table, and those are what is copied
here.

The values are strings, not numbers, because that is what the editor shows
and what the manual prints -- ``200 Hz``, ``BYPASS``, ``0.05 Hz``. Parsing
them to floats would lose the ones that are not a number.

Only the CHORUS and REVERB algorithms so far. The MFX has forty of them,
with up to thirty-two parameters each, and is the next piece of work.
"""

